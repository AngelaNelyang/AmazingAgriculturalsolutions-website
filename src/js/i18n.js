// Internationalization (i18n) module
// Bilingual support: English (default) and Kiswahili
// Stores preference in localStorage; persists across pages; no reloads.

const STORAGE_KEY = 'aas_lang'
export const LANGS = ['en', 'sw']
export const DEFAULT_LANG = 'en'

export function getLang() {
  const saved = localStorage.getItem(STORAGE_KEY)
  return LANGS.includes(saved) ? saved : DEFAULT_LANG
}

export function setLang(lang) {
  if (!LANGS.includes(lang)) return
  localStorage.setItem(STORAGE_KEY, lang)
  applyTranslations(lang)
  document.documentElement.lang = lang
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }))
}

// Apply translations to all elements with data-i18n attributes.
export function applyTranslations(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS[DEFAULT_LANG]
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n')
    if (dict[key] != null) el.textContent = dict[key]
  })
  // Placeholder translations for form inputs
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder')
    if (dict[key] != null) el.setAttribute('placeholder', dict[key])
  })
  // ARIA-label translations
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria')
    if (dict[key] != null) el.setAttribute('aria-label', dict[key])
  })
  document.documentElement.lang = lang
}

